/**
 * Formats regression comparison results into a GitHub-flavored Markdown report.
 */

export function generateMarkdownReport(baseline, candidate, comparison, aiSummary = null) {
  const { summary, testResults, metrics, candidateDiagnostics } = comparison;

  const isCritical = summary.verdict === 'CRITICAL_REGRESSION';
  const badgeTone = isCritical ? '🔴 CRITICAL REGRESSIONS DETECTED' : '🟢 ALL TESTS PASSING';

  let md = `# 🛡️ Firmware Regression Report\n\n`;

  // 1. Executive Status Callout
  md += `> **Status:** **${badgeTone}**  \n`;
  md += `> **Baseline:** \`${baseline.metadata.filename}\` (${baseline.metadata.kernel || 'Kernel N/A'}, Build: ${baseline.metadata.buildTag || 'N/A'})  \n`;
  md += `> **Candidate:** \`${candidate.metadata.filename}\` (${candidate.metadata.kernel || 'Kernel N/A'}, Build: ${candidate.metadata.buildTag || 'N/A'})\n\n`;

  // 2. High-level Metrics Summary Cards
  md += `| Total Tests | Passing | Regressions | Missing Tests | Boot Time Delta | Memory Anomalies |\n`;
  md += `| :---: | :---: | :---: | :---: | :---: | :---: |\n`;

  const bootDeltaStr = metrics.bootTime 
    ? `${metrics.bootTime.diffSec > 0 ? '+' : ''}${metrics.bootTime.diffSec}s (${metrics.bootTime.pctChange > 0 ? '+' : ''}${metrics.bootTime.pctChange}%)` 
    : 'N/A';

  const memAnomalyCount = metrics.memory.filter(m => m.isRegressed).length;

  md += `| ${summary.totalCandidateTests} | ${summary.totalPassing} | ${summary.totalRegressions > 0 ? `**${summary.totalRegressions}** ❌` : '0 ✅'} | ${summary.totalMissing > 0 ? `**${summary.totalMissing}** ⚠️` : '0 ✅'} | ${bootDeltaStr} | ${memAnomalyCount > 0 ? `**${memAnomalyCount} Alert(s)** ⚠️` : 'Normal ✅'} |\n\n`;

  // 3. AI / Engineering Triage Summary (if present)
  if (aiSummary) {
    md += `## 🧠 Diagnostic Analysis & Root-Cause Hypotheses\n\n`;
    md += `${aiSummary}\n\n`;
    md += `---\n\n`;
  }

  // 4. Test Results Matrix
  md += `## 📋 Test Results Matrix\n\n`;
  md += `| Suite | Test Case | Baseline | Candidate | Duration Δ | Detail / Failure Reason |\n`;
  md += `| :--- | :--- | :---: | :---: | :---: | :--- |\n`;

  for (const t of testResults) {
    const statusIcon = 
      t.category === 'REGRESSION' ? '❌ **REGRESSION**' :
      t.category === 'MISSING_COVERAGE' ? '⚠️ **MISSING**' :
      t.category === 'FIXED' ? '✨ **FIXED**' :
      t.candidateStatus === 'PASS' ? '✅ PASS' : '❌ FAIL';

    const durDelta = t.durationChangeMs !== null ? `${t.durationChangeMs > 0 ? '+' : ''}${t.durationChangeMs} ms` : '-';
    const reasonText = t.reason ? t.reason : (t.category === 'UNCHANGED_PASS' ? 'Normal execution' : '-');

    md += `| \`${t.suite}\` | \`${t.name}\` | \`${t.baselineStatus}\` | ${statusIcon} | ${durDelta} | ${reasonText} |\n`;
  }
  md += `\n`;

  // 5. System Performance & Resource Metrics
  md += `## 📊 Resource & Performance Profiling\n\n`;
  
  if (metrics.bootTime) {
    md += `### Boot Duration\n`;
    md += `- **Baseline Boot Time:** \`${metrics.bootTime.baselineSec}s\`\n`;
    md += `- **Candidate Boot Time:** \`${metrics.bootTime.candidateSec}s\` (${metrics.bootTime.isRegressed ? '⚠️ **REGRESSION DETECTED**' : '✅ Stable'})\n`;
    md += `- **Difference:** \`${bootDeltaStr}\`\n\n`;
  }

  if (metrics.memory.length > 0) {
    md += `### Daemon Memory Profiling (\`VmRSS\`)\n\n`;
    md += `| Daemon / Service | Baseline VmRSS | Candidate VmRSS | Memory Δ (kB) | % Change | Health |\n`;
    md += `| :--- | :---: | :---: | :---: | :---: | :---: |\n`;

    for (const m of metrics.memory) {
      const health = m.isRegressed ? '⚠️ **ANOMALY (+25%+)**' : '✅ Stable';
      const changeSign = m.diffKb > 0 ? '+' : '';
      md += `| \`${m.service}\` | ${m.baselineRssKb.toLocaleString()} kB | ${m.candidateRssKb.toLocaleString()} kB | ${changeSign}${m.diffKb.toLocaleString()} kB | ${changeSign}${m.pctChange}% | ${health} |\n`;
    }
    md += `\n`;
  }

  // 6. Evidence & Diagnostic Log Trace
  md += `## 🔍 Critical Log Evidence & Citations\n\n`;
  md += `The following diagnostic lines were captured directly from the candidate run log (\`${candidate.metadata.filename}\`):\n\n`;
  md += `\`\`\`text\n`;
  for (const diag of candidateDiagnostics) {
    md += `Line ${diag.lineNumber.toString().padStart(3, ' ')}: ${diag.text}\n`;
  }
  md += `\`\`\`\n\n`;

  // 7. Footer & Pilot Inquiry Callout
  md += `---\n\n`;
  md += `*Report automatically generated by [firmware-regression-reporter](https://github.com/ahussein1992/firmware-regression-reporter) — Developed by **Ahmed Hussein** (Senior Embedded Linux & Networking Engineer).*  \n`;
  md += `*Interested in automating firmware test reporting or diagnosing complex regressions on your embedded devices? Inquire for a fixed-scope pilot engagement.*`;

  return md;
}
